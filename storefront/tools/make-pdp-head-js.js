// Generates the Unas head tag in its JS-only form (Unas wraps the tag content in a <script> element, so the
// styles are injected from JS): switch + all inline CSS (v11 + v2 + v2 body) + async loader.
//   NODE_PATH=<playwright node_modules> node storefront/tools/make-pdp-head-js.js <commit> storefront/kbd-pdp-head.unas.js
// Run it after every change in kbd-pdp.js / kbd-pdp2.js / kbd-pdp2-body.js, then paste the output into the Unas head field.
const { chromium } = require('playwright'); const fs = require('fs'); const path = require('path');
const [,, commit, out] = process.argv;
const dir = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(dir, f), 'utf8');
const IDS = ['kbd-pdp-css', 'kbd-pdp-css2', 'kbd-pdp-css3', 'kbd-pdp-css0', 'kbd-pdp-v2css', 'kbd-pdp-v2body-css'];
(async () => {
  const b = await chromium.launch(); const res = {};
  for (const host of ['https://kicksbydavid.hu/x', 'https://www.kicksbydavid.sk/x']) {
    const p = await b.newPage();
    await p.route('**/*', r => r.request().resourceType() === 'document' ? r.fulfill({ status: 200, contentType: 'text/html', body: '<!doctype html><html><head></head><body></body></html>' }) : r.abort());
    await p.goto(host);
    await p.addScriptTag({ content: read('kbd-pdp.js') });
    await p.evaluate(() => document.documentElement.classList.add('kbd-pdp', 'kbd-v2'));
    await p.addScriptTag({ content: read('kbd-pdp2.js') });
    await p.addScriptTag({ content: read('kbd-pdp2-body.js') });
    res[host] = await p.evaluate(ids => ids.map(id => { const e = document.getElementById(id); return e ? e.textContent : null; }), IDS);
    await p.close();
  }
  await b.close();
  const [hu, sk] = Object.values(res);
  if (JSON.stringify(hu) !== JSON.stringify(sk)) throw new Error('CSS differs between HU and SK');
  if (hu.some(x => !x)) throw new Error('missing style block: ' + hu.map((x, i) => x ? '' : IDS[i]).join(','));
  const sw = '(function(){var on=true;try{var q=location.search,ls=window.localStorage;' +
    'if(/[?&]kbdnew=1/.test(q))ls.setItem("kbdnew","1");if(/[?&]kbdnew=0/.test(q))ls.removeItem("kbdnew");if(/[?&]kbdoff=1/.test(q))on=false;' +
    'if(/[?&]kbdv2=1/.test(q))ls.setItem("kbdv2","1");if(/[?&]kbdv2=0/.test(q))ls.setItem("kbdv2","0");}catch(e){}if(!on)return;' +
    'var h=document.documentElement;h.classList.add("kbd-pdp");' +
    'var LIVE={hu:true,sk:true},v=null;try{v=window.localStorage.getItem("kbdv2");}catch(e){}' +
    'var sk=/\\.sk$/i.test(location.hostname)||(h.getAttribute("lang")||"").toLowerCase().indexOf("sk")===0;' +
    'if(v==="1"||(v!=="0"&&(sk?LIVE.sk:LIVE.hu)))h.classList.add("kbd-v2");' +
    'function rdy(){setTimeout(function(){h.classList.add("kbd-ready");},3000);}if(document.readyState==="loading")document.addEventListener("DOMContentLoaded",rdy);else rdy();})();';
  const style = (id, css, v2) => '(function(){var h=document.documentElement;if(!h.classList.contains("kbd-pdp")' + (v2 ? '||!h.classList.contains("kbd-v2")' : '') + '||document.getElementById("' + id + '"))return;var s=document.createElement("style");s.id="' + id + '";s.textContent=' + JSON.stringify(css) + ';(document.head||h).appendChild(s);})();';
  const loader = '(function(){if(!document.documentElement.classList.contains("kbd-pdp")||document.getElementById("kbd-pdp-loader"))return;var s=document.createElement("script");s.id="kbd-pdp-loader";s.async=true;s.src="https://cdn.jsdelivr.net/gh/vazsan/kicksbydavid-price-service@' + commit + '/storefront/kbd-pdp.js";(document.head||document.documentElement).appendChild(s);})();';
  const header = '/* KicksByDavid termekoldal v13 head loader (JS-only, generated by storefront/tools/make-pdp-head-js.js @' + commit.slice(0, 7) + '). Unas wraps tag content in a script element, so styles are injected via JS. Regenerate after every kbd-pdp*.js change. */\n';
  const body = header + sw + '\n' + IDS.map((id, i) => style(id, hu[i], i >= 4)).join('\n') + '\n' + loader + '\n';
  fs.writeFileSync(out, body);
  console.log('written', out, body.length, 'bytes');
})();
